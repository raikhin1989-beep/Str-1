-- Оценка «насколько нравится» — по раундам, а не одна на образец.
--
-- Поймано на живой дегустации: «бегунок не вернулся в среднее положение при
-- переходе между раундами». И правда — оценка хранилась одна на образец,
-- поэтому в раунде по вкусу гость видел то, что поставил по запаху. Это и
-- сбивает, и обесценивает вторую оценку: попробовав, человек часто меняет
-- мнение, а перезаписывать первое впечатление молча неправильно.
--
-- Теперь как у тегов: JSON по раундам. Колонка score остаётся и хранит
-- последнее осознанное мнение (вкус, если он есть, иначе запах) — по ней
-- считается «виски вечера», и переписывать этот запрос незачем.
ALTER TABLE rating ADD COLUMN scores TEXT;
