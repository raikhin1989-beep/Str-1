-- Выкинуть из кэша распознавания то, что распознать не удалось.
--
-- Кэш вечный и ключуется хешем картинки (или названием). Пока у нас не было
-- прав на чтение этикетки, каждая принесённая фотография получала отказ —
-- и этот отказ оседал в кэше. Права выдали, а те же самые фотографии
-- продолжали получать старый ответ: мгновенно, мимо модели, навсегда.
--
-- Поймано на живом сайте 4 августа: фотография Laphroaig, снятая 31 июля,
-- отвечала «фотография не приложена» уже после того, как OCR заработал.
--
-- Записывать неудачи мы перестали (см. ai._to_cache), здесь убираем осевшие.
-- Удачные карточки не трогаем: они по-прежнему экономят запрос к модели.
