-- Ответ «только класс» тоже должен уметь замораживаться.
--
-- Поймано на живой дегустации по регионам. Гость выбирал регион, не трогая
-- названия, и нажимал «Отправить». Баллы начислялись правильно, а вот
-- состояние вечера читалось только из таблицы answer — где у такого гостя
-- ни одной строки. Отсюда:
--
--   * в админке «сдали 0 из 2», хотя сдали оба;
--   * колонки «Запах» и «Вкус» показывали «—»;
--   * round_submitted возвращал False, то есть ответ не считался
--     отправленным и гость видел форму заново — как будто ничего не сохранил.
--
-- Признак отправки теперь есть и здесь, и ставится тем же движением:
-- кнопкой «Отправить» и закрытием раунда.
ALTER TABLE answer_category ADD COLUMN submitted_at TEXT;

-- Уже сыгранное чинить нечем и незачем: считать его отправленным вернее,
-- чем оставить в подвешенном состоянии. Эта таблица появилась сегодня,
-- в ней только сегодняшний тест.
UPDATE answer_category SET submitted_at = CURRENT_TIMESTAMP WHERE submitted_at IS NULL;
