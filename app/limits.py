"""Ограничение частоты запросов на публичных формах.

Счётчик в памяти процесса: приложение одно, переживать перезапуск ему незачем,
а лишняя таблица в базе на каждый клик — плохая цена за защиту от шалости.

Ограничение здесь не про взлом, а про то, чтобы шутник с телефона не завёл
двести участников за минуту и не сорвал вечер.

**Чем считать — важнее, чем сколько.** Дегустация идёт в одной квартире, и все
гости выходят в интернет через один роутер: снаружи это один адрес. Значит
счётчик по адресу считает не человека, а всю компанию — и наказывает как раз
её, а не шутника, который придёт со своего мобильного интернета. Поэтому:

* где есть личная ссылка (черновик раунда) — считаем по ней. Токен — это ровно
  один гость, и перебрать он может только собственный черновик;
* где её ещё нет (регистрация) — считаем по адресу, но с потолком, в который
  свободно помещается компания. Двести записей за минуту он всё равно не даст.
"""

import time

# Сколько действий с одного счётчика за окно.
LIMITS = {
    # Регистраций за 10 минут с одного адреса. Гости записываются все разом,
    # в первые минуты вечера, и все — из одной сети. Было 10, и одиннадцатый
    # человек получал отказ на пороге: проверено, см. tests/test_limits.py.
    "join": (60, 600),
    # Автосохранений черновика за 10 минут с одной личной ссылки. Черновик
    # уходит через полсекунды после каждой правки; за раунд их десятки,
    # но у одного человека, а не у стола.
    "draft": (240, 600),
}

_seen: dict[tuple[str, str], list[float]] = {}


class TooOften(Exception):
    """Слишком часто с одного адреса."""


def check(kind: str, subject: str) -> None:
    """Учесть действие. subject — адрес или личный токен, смотря что считаем."""
    limit, window = LIMITS[kind]
    now = time.time()
    key = (kind, subject)
    recent = [moment for moment in _seen.get(key, []) if now - moment < window]
    _seen[key] = recent
    if len(recent) >= limit:
        raise TooOften
    recent.append(now)


def reset() -> None:
    """Забыть счётчики — нужно тестам."""
    _seen.clear()
