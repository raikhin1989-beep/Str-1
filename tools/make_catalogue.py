def sql_value(value) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


HEADER = """-- Справочник ходовых виски: то, из чего участники выбирают ответ.
--
-- Составлен целиком нами, а не скопирован из магазина: описания и ноты
-- в каталогах WineStyle, Декантера и Whiskybase — их контент, и
-- перепубликовывать его нельзя. Цена — ориентир для российской розницы
-- на август 2026, а не котировка.
--
-- Всё уезжает с source='ai': крепость и возраст даны по стандартным розливам,
-- у трэвел-ретейла и старых партий они другие. На публичной карточке из-за
-- этого стоит пометка «данные ориентировочные». Для конкретного вечера админ
-- сверяет цифры с бутылкой и правит руками — так сделано для пяти бутылок
-- первой дегустации (см. docs/TASTING-001.md).
--
-- Файл сгенерирован: python3 tools/make_catalogue.py
-- INSERT берёт только те названия, которых ещё нет: повторный прогон
-- миграции ничего не задвоит, а правки из админки не затрёт.
"""

TEMPLATE = """
INSERT INTO whisky (name, distillery, wclass, region, abv, age_years, cask, grain,
                    filtration, price_rub, colour, nose, palate, finish, notes, source)
SELECT {values}, 'Данные ориентировочные: сверьте крепость и цену с бутылкой.', 'ai'
WHERE NOT EXISTS (SELECT 1 FROM whisky WHERE name = {name});
"""


def existing_names() -> list[str]:
    """Названия, которые останутся в справочнике после предыдущих миграций.

    Читаем не текст миграций, а результат: 004 не только добавляет бутылки,
    но и удаляет заведённые 002 «на словах». Название, которое там удалено,
    свободно, и брать его в расчёт нельзя.
    """
    conn = sqlite3.connect(":memory:")
    try:
        for path in sorted(OUT.parent.glob("*.sql")):
            if path == OUT:
                continue
            conn.executescript(path.read_text(encoding="utf-8"))
        return [row[0] for row in conn.execute("SELECT name FROM whisky")]
    finally:
        conn.close()


def assert_no_variants(names: list[str]) -> None:
    """Одна бутылка — одно имя.

    Точные повторы отсекает сам INSERT, а вот «Dewar's 12» рядом с уже
    заведённым «Dewar's 12 Year Old» он пропустит — и в списке ответов
    окажется два имени одного виски. Приблизительное имя почти всегда
    получается приставкой к полному, поэтому и проверяем приставки.
    """
    known = existing_names()
    for name in names:
        for other in known:
            short, long = sorted((name.casefold(), other.casefold()), key=len)
            if short != long and long.startswith(short + " "):
                raise AssertionError(
                    f"«{name}» и «{other}» — похоже, одна бутылка под двумя именами"
                )


def main() -> None:
    names = [row[0] for row in WHISKIES]
    assert len(names) == len(set(names)), "в списке есть повторы названий"
    assert_no_variants(names)

    parts = [HEADER]
    for row in WHISKIES:
        values = ", ".join(sql_value(value) for value in row)
        parts.append(TEMPLATE.format(values=values, name=sql_value(row[0])))
    OUT.write_text("".join(parts), encoding="utf-8")
    print(f"{OUT} — {len(WHISKIES)} записей, {OUT.stat().st_size} байт")


if __name__ == "__main__":
    main()
